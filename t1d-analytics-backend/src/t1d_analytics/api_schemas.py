class ExecuteSqlResponse(BaseModel):
    """Response model for the execute SQL endpoint."""

    model_config = ConfigDict(populate_by_name=True)

    sql_result: list[dict[str, SqlValue]] | None = Field(
        default=None, alias="sqlResult"
    )
    rows: list[dict[str, SqlValue]] | None = Field(
        default=None, deprecated="Use sqlResult instead."
    )
    error: ApiError | None = None

    @model_validator(mode="after")
    def _sync_deprecated_rows_alias(self) -> "ExecuteSqlResponse":
        """Synchronize `sql_result` and deprecated `rows` when only one is supplied."""
        if self.sql_result is None and self.rows is not None:
            self.sql_result = self.rows
        elif self.rows is None and self.sql_result is not None:
            self.rows = self.sql_result
        return self


