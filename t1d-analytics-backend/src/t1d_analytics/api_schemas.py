"""Strongly-typed Pydantic request and response schemas for the T1D Analytics REST API."""

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator
from pydantic.alias_generators import to_camel

from t1d_analytics.sql_utils import SqlValue

ChatJobStatus = Literal["pending", "complete", "failed"]


class ApiError(BaseModel):
    """Structured API error format."""

    error_code: str
    params: dict[str, SqlValue] = Field(default_factory=dict)


class SqlGoldComparisonModel(BaseModel):
    """
    Evaluation metrics comparing an LLM-generated SQL query against a Gold-Standard SQL query on the read-only DuckDB cursor.

    Attributes:
        gold_sql: Canonical gold-standard DuckDB SQL query.
        pred_sql: SQL query generated by the target LLM.
        exact_match: Whether normalized `pred_sql` matches normalized `gold_sql`.
        execution_accuracy: Whether executing `pred_sql` and `gold_sql` on the read-only DuckDB cursor yields equivalent result sets.
        syntax_error: Whether `pred_sql` raised a DuckDB syntax/binder/execution error.
        gold_row_count: Total rows returned by `gold_sql` on the read-only cursor.
        pred_row_count: Total rows returned by `pred_sql` on the read-only cursor.
        gold_columns: Ordered column names returned by `gold_sql`.
        pred_columns: Ordered column names returned by `pred_sql`.
        column_overlap_pct: Value/cell multiset approximation percentage (0.0 to 100.0) between predicted and gold results.
        gold_rows_preview: Preview rows from executing `gold_sql` on the read-only DuckDB cursor.
        error_message: Optional diagnostic error message if `pred_sql` failed execution.

    """

    gold_sql: str
    pred_sql: str
    exact_match: bool = False
    execution_accuracy: bool = False
    syntax_error: bool = False
    gold_row_count: int = 0
    pred_row_count: int = 0
    gold_columns: list[str] = Field(default_factory=list)
    pred_columns: list[str] = Field(default_factory=list)
    column_overlap_pct: float = 0.0
    gold_rows_preview: list[dict[str, SqlValue]] = Field(default_factory=list)
    error_message: str | None = None


